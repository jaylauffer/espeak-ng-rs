#!/usr/bin/env python3
"""Freeze this fork's initialized language presets into native Rust tables.

Only regeneration uses a C compiler. Cargo uses committed immutable tables.
All switch selectors and the default branch are covered. Wide tables are
exported as scalar/code-unit values, never native pointers or struct bytes.
"""
